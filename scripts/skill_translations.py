"""Prepare and apply local Chinese display labels for registered Skills.

Translations are generated by the user's local Agent from this small JSON file;
this tool never calls a model or sends data over the network.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parents[1]
import sys
sys.path.insert(0, str(ROOT))
from backend.workspace.errors import WorkspaceError
from backend.workspace.files import collect
from backend.workspace.router import dispatch
from backend.workspace.service import Workspace
from backend.skill_files import find_skill_md
from scripts.catalog_presentation import description_hash, load_skill_translation_cache

CACHE_NAME = "skill-translations.zh-CN.json"
HAN = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff]")


def _text(value):
    return value if isinstance(value, str) and value.strip() else ""


def _metadata(asset, collected=None):
    """Return the original Skill name/description and the source document hash."""
    source = asset.get("source", {})
    if source.get("type") != "path":
        raise ValueError("SKILL_SOURCE_NOT_FILE")
    folder = Path(source["path"])
    collected = collected if collected is not None else collect("skill", source)
    if (collected["entries"] != asset.get("files") or collected["omissions"] != asset.get("omissions")
            or collected["followUps"] != asset.get("followUps")):
        raise ValueError("SOURCE_CHANGED")
    document = find_skill_md(folder)
    if document is None:
        raise ValueError("SKILL_DOCUMENT_MISSING")
    rel = document.relative_to(folder).as_posix()
    raw = collected["files"].get(rel)
    if raw is None:
        raise ValueError("SKILL_DOCUMENT_MISSING")
    body = raw.decode("utf-8-sig")
    digest = hashlib.sha256(raw).hexdigest()
    saved_value = (asset.get("environment") or {}).get("presentation")
    saved = saved_value if isinstance(saved_value, dict) else {}
    presentation_is_current = saved.get("sourceFile") == document.name and saved.get("sourceSha256") == digest
    original_name = _text(saved.get("originalName")) if presentation_is_current else ""
    original_description = _text(saved.get("originalDescription")) if presentation_is_current else ""
    # Existing reader metadata is content-fingerprinted by the caller. Fall back
    # to the small, conventional SKILL.md header for older registered assets.
    if not original_name or not original_description:
        header = ""
        if body.startswith("---\n") or body.startswith("---\r\n"):
            match = re.match(r"\A---\r?\n(.*?)\r?\n---(?:\r?\n|\Z)", body, re.S)
            if match:
                header = match.group(1)
        if header:
            try:
                import yaml
                parsed = yaml.safe_load(header)
                if isinstance(parsed, dict):
                    original_name = original_name or _text(parsed.get("name"))
                    original_description = original_description or _text(parsed.get("description"))
            except ImportError:
                # Common single-line headers remain usable without PyYAML.
                name_match = re.search(r"(?m)^name:\s*(.*?)\s*$", header)
                desc_match = re.search(r"(?m)^description:\s*(.*?)\s*$", header)
                if name_match:
                    original_name = original_name or name_match.group(1).strip(" '\"")
                if desc_match and desc_match.group(1) not in {"|", ">", "|-", ">-"}:
                    original_description = original_description or desc_match.group(1).strip(" '\"")
            except Exception as exc:
                raise ValueError("SKILL_METADATA_INVALID") from exc
    original_name = original_name or _text(asset.get("title"))
    return {"document": document, "documentHash": digest,
            "originalName": original_name, "originalDescription": original_description}


def _cache_path(home):
    return Path(home) / CACHE_NAME


def _read_cache(home):
    return {"schemaVersion": 1, "items": load_skill_translation_cache(home)}


def _write_cache(home, value):
    path = _cache_path(home)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            json.dump(value, stream, ensure_ascii=False, indent=2)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp_name, path)
    finally:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass


def prepare(workspace, output):
    cache = _read_cache(workspace.home)
    rows, skipped, already_translated, prefilled = [], [], 0, 0
    assets = workspace.assets(kind="skill", include_system=False)
    for asset in assets:
        try:
            meta = _metadata(asset)
            if not meta["originalDescription"]:
                skipped.append({"assetId": asset["id"], "reason": "缺少可翻译的用途说明"})
                continue
            if not meta["originalName"]:
                skipped.append({"assetId": asset["id"], "reason": "缺少 Skill 原名"})
                continue
            key = description_hash(meta["originalName"], meta["originalDescription"])
            env = asset.get("environment") or {}
            presentation_value = env.get("presentation")
            presentation = presentation_value if isinstance(presentation_value, dict) else {}
            valid_presentation = (presentation.get("sourceFile") == meta["document"].name
                and presentation.get("sourceSha256") == meta["documentHash"]
                and presentation.get("originalName") == meta["originalName"]
                and presentation.get("originalDescription") == meta["originalDescription"])
            if (valid_presentation and presentation.get("translation") == "中文简介"
                    and HAN.search(_text(presentation.get("summary")))
                    and HAN.search(_text(presentation.get("title")))):
                already_translated += 1
                continue
            cached = cache["items"].get(key, {})
            if cached:
                prefilled += 1
            rows.append({"assetId": asset["id"], "version": asset["version"],
                         "sourceSha256": meta["documentHash"], "originalName": meta["originalName"],
                         "originalDescription": meta["originalDescription"],
                         "titleZh": cached.get("titleZh", ""), "summaryZh": cached.get("summaryZh", "")})
        except (OSError, UnicodeError, ValueError, WorkspaceError) as exc:
            skipped.append({"assetId": asset.get("id", ""),
                            "reason": _reason(exc)})
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps({"schemaVersion": 1, "items": rows}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return {"prepared": len(rows), "alreadyTranslated": already_translated, "prefilledFromCache": prefilled,
            "skipped": skipped, "output": str(output)}


def _reason(exc):
    code = exc.code if isinstance(exc, WorkspaceError) else str(exc)
    return {"SOURCE_CHANGED": "Skill 文件已变化，请刷新资料后重新整理。",
            "SOURCE_MISSING": "Skill 文件不存在，请刷新资料后重试。",
            "SOURCE_UNREADABLE": "Skill 文件无法读取，请检查权限和编码。",
            "SKILL_DOCUMENT_MISSING": "找不到 Skill.md 文件。",
            "SKILL_SOURCE_NOT_FILE": "此 Skill 没有可读取的本地目录。",
            "DESCRIPTION_MISSING": "缺少可翻译的用途说明。",
            "SKILL_METADATA_INVALID": "Skill 文档头无法解析。",
            "TRANSLATION_CACHE_INVALID": "本地中文简介缓存格式无效，请检查档案文件。"}.get(code, "无法读取此 Skill，请刷新资料后重试。")


def _validate_translation(row):
    name = _text(row.get("originalName"))
    description = _text(row.get("originalDescription"))
    title = _text(row.get("titleZh"))
    summary = _text(row.get("summaryZh"))
    if not name or not description or not HAN.search(title) or not HAN.search(summary):
        raise ValueError("TRANSLATION_INCOMPLETE")
    if len(title) > 500 or len(summary) > 4000:
        raise ValueError("TRANSLATION_TOO_LARGE")
    return title, summary


def apply(workspace, input_path):
    document = json.loads(input_path.read_text(encoding="utf-8"))
    if not isinstance(document, dict) or document.get("schemaVersion") != 1 or not isinstance(document.get("items"), list):
        raise ValueError("TRANSLATION_FILE_INVALID")
    cache = _read_cache(workspace.home)
    updated, errors = 0, []
    for row in document["items"]:
        asset_id = row.get("assetId", "") if isinstance(row, dict) else ""
        try:
            if not isinstance(row, dict):
                raise ValueError("TRANSLATION_ITEM_INVALID")
            asset_id = row.get("assetId", "")
            asset = workspace.get_asset(asset_id)
            if asset.get("kind") != "skill" or asset.get("ownership") == "system":
                raise ValueError("ASSET_NOT_TRANSLATABLE")
            if asset.get("version") != row.get("version"):
                raise ValueError("VERSION_CONFLICT")
            collected = collect("skill", asset["source"])
            meta = _metadata(asset, collected)
            if meta["documentHash"] != row.get("sourceSha256"):
                raise ValueError("SOURCE_CHANGED")
            if meta["originalName"] != row.get("originalName") or meta["originalDescription"] != row.get("originalDescription"):
                raise ValueError("SOURCE_CHANGED")
            title, summary = _validate_translation(row)
            key = description_hash(meta["originalName"], meta["originalDescription"])
            presentation = {**((asset.get("environment") or {}).get("presentation") or {}),
                "schemaVersion": 1, "sourceFile": meta["document"].name, "sourceSha256": meta["documentHash"],
                "title": title, "summary": summary, "originalName": meta["originalName"],
                "originalDescription": meta["originalDescription"], "titleSource": "中文释义", "translation": "中文简介"}
            environment = {**(asset.get("environment") or {}), "presentation": presentation}
            # Existing workspace contract updates display metadata while retaining
            # the selected source, scope, ownership and all other environment keys.
            # Recheck the asset version just before writing. The current file
            # asset API has no expectedVersion compare-and-swap guarantee.
            if workspace.get_asset(asset_id).get("version") != row.get("version"):
                raise ValueError("VERSION_CONFLICT")
            dispatch(workspace, "POST", "/api/v1/assets", {"kind": "skill", "path": asset["source"]["path"],
                "title": asset["title"], "scope": asset["scope"], "ownership": asset["ownership"],
                "environment": environment})
            cache["items"][key] = {"titleZh": title, "summaryZh": summary}
            updated += 1
        except (KeyError, TypeError, ValueError, OSError, WorkspaceError) as exc:
            reason = exc.code if isinstance(exc, WorkspaceError) else str(exc)
            errors.append({"assetId": asset_id, "reason": reason or "TRANSLATION_ITEM_INVALID"})
    if updated:
        _write_cache(workspace.home, cache)
    return {"updated": updated, "errors": errors, "cache": str(_cache_path(workspace.home))}


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    prep = sub.add_parser("prepare", help="Export untranslated Skills for the local Agent to translate")
    prep.add_argument("--data-dir", required=True, type=Path)
    prep.add_argument("--output", required=True, type=Path)
    commit = sub.add_parser("apply", help="Apply translated display metadata without changing Skill files")
    commit.add_argument("--data-dir", required=True, type=Path)
    commit.add_argument("--input", required=True, type=Path)
    args = parser.parse_args(argv)
    if not args.data_dir.is_absolute():
        parser.error("--data-dir must be absolute")
    if not args.data_dir.is_dir() or not (args.data_dir / "profile.sqlite3").is_file():
        parser.error("--data-dir must be an existing workspace profile directory")
    workspace = Workspace(args.data_dir)
    result = prepare(workspace, args.output) if args.command == "prepare" else apply(workspace, args.input)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 2 if result.get("errors") or result.get("skipped") else 0


if __name__ == "__main__":
    raise SystemExit(main())
